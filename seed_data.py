def seed_full_categories(db, now):
    """幂等补齐所有行业的机构/业务/资料类型分类，返回新增条数。

    参数：db  —— sqlite3.Connection
          now —— 写入 created_at 的时间字符串
    说明：按 (parent_id, type, name) 判重，只追加缺失项；
          sort 接续该分类下现有最大序号，保持后台排序稳定。
    """
    added_total = 0
    for ind_name, groups in INDUSTRY_CATEGORIES.items():
        row = db.execute(
            "SELECT id FROM categories WHERE parent_id=0 AND type='industry' AND name=?",
            (ind_name,)).fetchone()
        if not row:
            max_sort = db.execute(
                "SELECT COALESCE(MAX(sort),0) FROM categories WHERE parent_id=0 AND type='industry'"
            ).fetchone()[0]
            db.execute(
                "INSERT INTO categories(parent_id,type,name,sort,status,created_at)"
                " VALUES(0,'industry',?,?,1,?)", (ind_name, max_sort + 1, now))
            row = db.execute(
                "SELECT id FROM categories WHERE parent_id=0 AND type='industry' AND name=?",
                (ind_name,)).fetchone()
        cid = row[0]
        for typ, items in groups.items():
            have = {r[0] for r in db.execute(
                "SELECT name FROM categories WHERE parent_id=? AND type=?", (cid, typ)).fetchall()}
            max_sort = db.execute(
                "SELECT COALESCE(MAX(sort),0) FROM categories WHERE parent_id=? AND type=?",
                (cid, typ)).fetchone()[0]
            for nm in items:
                if nm in have:
                    continue
                max_sort += 1
                db.execute(
                    "INSERT INTO categories(parent_id,type,name,sort,status,created_at)"
                    " VALUES(?,?,?,?,1,?)", (cid, typ, nm, max_sort, now))
                have.add(nm)
                added_total += 1
    return added_total
